-- 1. Create Telemetry Logs Table for Arduino Sensor Readings
CREATE TABLE IF NOT EXISTS public.telemetry_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pile_id TEXT NOT NULL,
    temp NUMERIC NOT NULL,
    moisture NUMERIC NOT NULL,
    ph NUMERIC NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Create Compost Piles Table
CREATE TABLE IF NOT EXISTS public.compost_piles (
    id TEXT PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'onTrack',
    temp NUMERIC NOT NULL DEFAULT 55.0,
    moisture NUMERIC NOT NULL DEFAULT 55.0,
    ph NUMERIC NOT NULL DEFAULT 7.0,
    readiness_percent NUMERIC DEFAULT 0,
    target_total_days INT DEFAULT 30,
    is_archived BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Enable Row Level Security (RLS) & Public Policies
ALTER TABLE public.telemetry_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.compost_piles ENABLE ROW LEVEL SECURITY;

-- Allow Arduino & App clients to read & insert telemetry logs
CREATE POLICY "Allow anon insert telemetry_logs"
ON public.telemetry_logs FOR INSERT
TO anon, authenticated
WITH CHECK (true);

CREATE POLICY "Allow public read telemetry_logs"
ON public.telemetry_logs FOR SELECT
TO anon, authenticated
USING (true);

-- Allow public read & insert compost_piles
CREATE POLICY "Allow public read compost_piles"
ON public.compost_piles FOR SELECT
TO anon, authenticated
USING (true);

CREATE POLICY "Allow public insert compost_piles"
ON public.compost_piles FOR INSERT
TO anon, authenticated
WITH CHECK (true);

CREATE POLICY "Allow public update compost_piles"
ON public.compost_piles FOR UPDATE
TO anon, authenticated
USING (true);

-- 4. Enable Supabase Realtime Stream for telemetry_logs
ALTER PUBLICATION supabase_realtime ADD TABLE public.telemetry_logs;
ALTER PUBLICATION supabase_realtime ADD TABLE public.compost_piles;

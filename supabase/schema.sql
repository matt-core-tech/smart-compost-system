-- Enable pgcrypto extension for gen_random_uuid()
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ----------------------------------------------------------
-- 1. CORE APPLICATION TABLES
-- ----------------------------------------------------------

-- Table: reserved_pile_numbers (Per-User Permanent Number Registry)
CREATE TABLE IF NOT EXISTS public.reserved_pile_numbers (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    pile_number INT NOT NULL CHECK (pile_number > 0),
    reserved_at TIMESTAMPTZ DEFAULT NOW(),
    original_pile_id UUID,
    CONSTRAINT reserved_pile_numbers_user_pile_key UNIQUE (user_id, pile_number)
);

-- Table: compost_piles
CREATE TABLE IF NOT EXISTS public.compost_piles (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    pile_number INT NOT NULL CHECK (pile_number > 0),
    name TEXT NOT NULL,
    category TEXT DEFAULT 'General Waste',
    start_date TIMESTAMPTZ DEFAULT NOW(),
    target_total_days INT DEFAULT 30,
    is_archived BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Ensure pile_number column exists on compost_piles
ALTER TABLE public.compost_piles ADD COLUMN IF NOT EXISTS pile_number INT;

-- Table: day_readings
CREATE TABLE IF NOT EXISTS public.day_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pile_id UUID NOT NULL REFERENCES public.compost_piles(id) ON DELETE CASCADE,
    day_number INT DEFAULT 1,
    reading_date DATE DEFAULT CURRENT_DATE,
    temp NUMERIC,          -- NULL when temperature sensor is unavailable
    moisture NUMERIC,      -- Raw ADC value (preserved for backward compatibility)
    raw_moisture NUMERIC,  -- Raw ADC value directly from sensor (e.g. 0 - 4095)
    moisture_pct NUMERIC,  -- Calibrated moisture percentage (0.0% - 100.0%)
    ph NUMERIC,            -- NULL when pH sensor is unavailable
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Ensure raw_moisture and moisture_pct columns exist on day_readings
ALTER TABLE public.day_readings ADD COLUMN IF NOT EXISTS raw_moisture NUMERIC;
ALTER TABLE public.day_readings ADD COLUMN IF NOT EXISTS moisture_pct NUMERIC;

-- ----------------------------------------------------------
-- 2. ADMIN DASHBOARD & SECURITY EXTENSION TABLES
-- ----------------------------------------------------------

-- Table: user_roles (Role-Based Access Control)
CREATE TABLE IF NOT EXISTS public.user_roles (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('admin', 'user')),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT user_roles_user_key UNIQUE (user_id)
);

-- Table: devices (ESP32 IoT Node Tracking)
CREATE TABLE IF NOT EXISTS public.devices (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    device_code TEXT UNIQUE NOT NULL,
    pile_id UUID REFERENCES public.compost_piles(id) ON DELETE SET NULL,
    last_seen TIMESTAMPTZ,
    is_online BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Table: audit_logs (Administrative Action & Security Event Logging)
CREATE TABLE IF NOT EXISTS public.audit_logs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    action TEXT NOT NULL,
    target_type TEXT,
    target_id TEXT,
    details JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW()
);


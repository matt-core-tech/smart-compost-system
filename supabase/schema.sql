-- Enable pgcrypto extension for gen_random_uuid()
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ----------------------------------------------------------
-- 1. TABLE: reserved_pile_numbers (PER-USER PERMANENT RESERVATIONS)
-- Tracks used pile numbers PER USER. Numbers remain reserved
-- forever, even if a pile is completed, archived, or deleted.
-- ----------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.reserved_pile_numbers (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    pile_number INT NOT NULL CHECK (pile_number > 0),
    reserved_at TIMESTAMPTZ DEFAULT NOW(),
    original_pile_id UUID, -- Optional reference (remains intact when pile is deleted)
    CONSTRAINT reserved_pile_numbers_user_pile_key UNIQUE (user_id, pile_number)
);

-- ----------------------------------------------------------
-- 2. TABLE: compost_piles
-- Primary records for active and archived compost piles.
-- user_id cannot be NULL for normal user-created records.
-- ----------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.compost_piles (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    pile_number INT NOT NULL CHECK (pile_number > 0),
    name TEXT NOT NULL,
    category TEXT DEFAULT 'General Waste',
    start_date TIMESTAMPTZ DEFAULT NOW(),
    target_total_days INT DEFAULT 30,
    is_archived BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT compost_piles_user_pile_key UNIQUE (user_id, pile_number)
);

-- Add Foreign Key from reserved_pile_numbers.original_pile_id to compost_piles.id (ON DELETE SET NULL)
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'reserved_pile_numbers_original_pile_id_fkey'
    ) THEN
        ALTER TABLE public.reserved_pile_numbers
        ADD CONSTRAINT reserved_pile_numbers_original_pile_id_fkey
        FOREIGN KEY (original_pile_id) REFERENCES public.compost_piles(id) ON DELETE SET NULL;
    END IF;
END $$;

-- ----------------------------------------------------------
-- 3. TABLE: day_readings
-- Telemetry log entries. Metrics (temp, moisture, ph) are NULLABLE.
-- ----------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.day_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pile_id UUID NOT NULL REFERENCES public.compost_piles(id) ON DELETE CASCADE,
    day_number INT DEFAULT 1,
    reading_date DATE DEFAULT CURRENT_DATE,
    temp NUMERIC,      -- NULL when sensor is disconnected/unavailable
    moisture NUMERIC,  -- Raw ADC or validated percentage
    ph NUMERIC,        -- NULL when pH sensor is unavailable
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ----------------------------------------------------------
-- 4. ROW LEVEL SECURITY (RLS) POLICIES
-- Strict Security: NO anonymous access (auth.uid() IS NULL removed).
-- Users can ONLY view, insert, update, or delete THEIR OWN records.
-- ----------------------------------------------------------
ALTER TABLE public.reserved_pile_numbers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.compost_piles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.day_readings ENABLE ROW LEVEL SECURITY;

-- Policies for reserved_pile_numbers
DROP POLICY IF EXISTS "Users can view their own reserved pile numbers" ON public.reserved_pile_numbers;
CREATE POLICY "Users can view their own reserved pile numbers"
ON public.reserved_pile_numbers FOR SELECT
TO authenticated
USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can insert their own reserved pile numbers" ON public.reserved_pile_numbers;
CREATE POLICY "Users can insert their own reserved pile numbers"
ON public.reserved_pile_numbers FOR INSERT
TO authenticated
WITH CHECK (auth.uid() = user_id);

-- Policies for compost_piles
DROP POLICY IF EXISTS "Users can view their own compost piles" ON public.compost_piles;
CREATE POLICY "Users can view their own compost piles"
ON public.compost_piles FOR SELECT
TO authenticated
USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can insert their own compost piles" ON public.compost_piles;
CREATE POLICY "Users can insert their own compost piles"
ON public.compost_piles FOR INSERT
TO authenticated
WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can update their own compost piles" ON public.compost_piles;
CREATE POLICY "Users can update their own compost piles"
ON public.compost_piles FOR UPDATE
TO authenticated
USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can delete their own compost piles" ON public.compost_piles;
CREATE POLICY "Users can delete their own compost piles"
ON public.compost_piles FOR DELETE
TO authenticated
USING (auth.uid() = user_id);

-- Policies for day_readings
-- Users can ONLY view readings belonging to their own compost piles
DROP POLICY IF EXISTS "Users can view readings of their compost piles" ON public.day_readings;
CREATE POLICY "Users can view readings of their compost piles"
ON public.day_readings FOR SELECT
TO authenticated
USING (
    EXISTS (
        SELECT 1 FROM public.compost_piles
        WHERE public.compost_piles.id = public.day_readings.pile_id
        AND public.compost_piles.user_id = auth.uid()
    )
);

-- Insertion policy for day_readings:
-- Authenticated users or API clients with valid pile access can insert sensor readings
DROP POLICY IF EXISTS "Users can insert readings for their compost piles" ON public.day_readings;
CREATE POLICY "Users can insert readings for their compost piles"
ON public.day_readings FOR INSERT
TO authenticated, anon
WITH CHECK (
    EXISTS (
        SELECT 1 FROM public.compost_piles
        WHERE public.compost_piles.id = public.day_readings.pile_id
    )
);

-- ----------------------------------------------------------
-- 5. TRANSACTIONAL ATOMIC PILE CREATION PROCEDURE
-- Creates reservation and compost_piles record within a single
-- atomic transaction using the authenticated user's ID.
-- ----------------------------------------------------------
CREATE OR REPLACE FUNCTION public.create_compost_pile_with_reservation(
    p_pile_number INT,
    p_name TEXT,
    p_category TEXT DEFAULT 'General Waste',
    p_target_days INT DEFAULT 30
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_user_id UUID;
    v_pile_id UUID;
    v_result JSONB;
BEGIN
    -- 1. Enforce authenticated user context
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Authentication required. User is not logged in.';
    END IF;

    -- 2. Validate pile_number
    IF p_pile_number IS NULL OR p_pile_number <= 0 THEN
        RAISE EXCEPTION 'Pile ID must be a positive integer greater than zero.';
    END IF;

    -- 3. Check for existing reservation for this user
    IF EXISTS (
        SELECT 1 FROM public.reserved_pile_numbers
        WHERE user_id = v_user_id AND pile_number = p_pile_number
    ) THEN
        RAISE EXCEPTION 'Pile ID #% has already been reserved for your account. Please choose a different numeric ID.', p_pile_number;
    END IF;

    -- 4. Atomically insert into reserved_pile_numbers
    INSERT INTO public.reserved_pile_numbers (user_id, pile_number)
    VALUES (v_user_id, p_pile_number);

    -- 5. Atomically insert into compost_piles
    INSERT INTO public.compost_piles (user_id, pile_number, name, category, target_total_days)
    VALUES (v_user_id, p_pile_number, p_name, p_category, p_target_days)
    RETURNING id INTO v_pile_id;

    -- 6. Link original_pile_id in reserved_pile_numbers
    UPDATE public.reserved_pile_numbers
    SET original_pile_id = v_pile_id
    WHERE user_id = v_user_id AND pile_number = p_pile_number;

    -- 7. Return created pile details as JSON
    SELECT to_jsonb(p.*) INTO v_result
    FROM public.compost_piles p
    WHERE p.id = v_pile_id;

    RETURN v_result;
END;
$$;

-- ----------------------------------------------------------
-- 6. IDEMPOTENT REALTIME PUBLICATION SETUP
-- ----------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables
        WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'compost_piles'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.compost_piles;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables
        WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'day_readings'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.day_readings;
    END IF;
END $$;

